use crate::helpers::{run_check, run_check_with, write};
use crate::test_types::SizeLimitCheckTestCase;

const PYTHON_BUCKETS: &[(&str, &str)] = &[
    ("src/pkg/orders/_helpers/__init__.py", ""),
    ("src/pkg/orders/_helpers/pricing/rates.py", ""),
    ("src/pkg/orders/_helpers/shipping/zones.py", ""),
    ("src/pkg/orders/_helpers/tax/regions.py", ""),
    ("src/pkg/orders/_helpers/assets/rates.json", "{}"),
];

const PYTHON_PACKAGE: &[(&str, &str)] = &[
    ("src/pkg/__init__.py", ""),
    ("src/pkg/orders/__init__.py", "\"\"\"Orders.\"\"\"\n"),
    (
        "src/pkg/orders/models.py",
        "# Order totals.\n\ncount: int = 1\nlimit: int = 2\n\nlabel: str = 'orders'  # shown\n",
    ),
];

const RUST_WORKSPACE: &[(&str, &str)] = &[
    (
        "Cargo.toml",
        "[workspace]\nmembers = [\"crates/orders\"]\nresolver = \"2\"\n",
    ),
    (
        "Cargo.lock",
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"orders\"\nversion = \"0.1.0\"\n",
    ),
    (
        "crates/orders/Cargo.toml",
        "[package]\nname = \"orders\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
    ),
    (
        "crates/orders/src/lib.rs",
        "// Order totals.\npub fn total() -> usize {\n\n    1\n}\n#[cfg(test)]\nmod tests {}\n",
    ),
    (
        "crates/orders/src/pricing/_helpers/rates/support.rs",
        "/// Rate support.\npub fn support() -> usize { 1 }\n",
    ),
    (
        "crates/orders/src/pricing/_helpers/taxes/support.rs",
        "pub fn support() -> usize { 1 }\n",
    ),
    (
        "crates/orders/src/pricing/_helpers/zones/support.rs",
        "pub fn support() -> usize { 1 }\n",
    ),
    (
        "crates/orders/src/pricing/_helpers/assets/rates.json",
        "{}\n",
    ),
    (
        "crates/orders/tests/totals.rs",
        "#[test]\nfn totals() {\n    assert_eq!(1, 1);\n}\n",
    ),
];

#[test]
fn given_size_limits_when_checking_natively_then_overrides_exceptions_and_cache_apply() {
    let test_cases = [
        SizeLimitCheckTestCase {
            description: "helpers container over its bucket limit is reported once",
            config: "roots = [\"src/pkg\"]\nselect = [\"FFR312\"]\n[thresholds]\nmax_helpers_container_buckets = 2\n",
            files: PYTHON_BUCKETS,
            expected_exit_code: 1,
            expected_present: &["--> src/pkg/orders/_helpers/__init__.py", "FFR312  _helpers/ holds 3 buckets (limit 2); split the owning module by area or move cohesive groups into their own module or crate."],
            expected_absent: "Threshold override:",
        },
        SizeLimitCheckTestCase {
            description: "helpers container at an overridden bucket limit passes",
            config: "roots = [\"src/pkg\"]\nselect = [\"FFR312\"]\n[thresholds]\nmax_helpers_container_buckets = 2\n[[threshold_overrides]]\npaths = [\"src/pkg/orders/_helpers/__init__.py\"]\nreason = \"Order helpers are being split.\"\nthresholds = { max_helpers_container_buckets = 3 }\n",
            files: PYTHON_BUCKETS,
            expected_exit_code: 0,
            expected_present: &["Threshold override: max_helpers_container_buckets=3", "Found 0 faults"],
            expected_absent: "FFR312  ",
        },
        SizeLimitCheckTestCase {
            description: "package over its code-line limit is reported at the root anchor",
            config: "roots = [\"src/pkg\"]\nselect = [\"FFR602\"]\n[thresholds]\nmax_crate_code_lines = 3\n",
            files: PYTHON_PACKAGE,
            expected_exit_code: 1,
            expected_present: &["--> src/pkg/__init__.py", "FFR602  package holds 4 code lines (limit 3); split it into packages by area."],
            expected_absent: "Threshold override:",
        },
        SizeLimitCheckTestCase {
            description: "package at an overridden code-line limit passes",
            config: "roots = [\"src/pkg\"]\nselect = [\"FFR602\"]\n[thresholds]\nmax_crate_code_lines = 3\n[[threshold_overrides]]\npaths = [\"src/pkg/**\"]\nreason = \"The package is being split.\"\nthresholds = { max_crate_code_lines = 4 }\n",
            files: PYTHON_PACKAGE,
            expected_exit_code: 0,
            expected_present: &["Threshold override: max_crate_code_lines=4", "Found 0 faults"],
            expected_absent: "FFR602  ",
        },
        SizeLimitCheckTestCase {
            description: "helpers container over its bucket limit is reported at the container",
            config: concat!(
                "[targets.rust]\nanalyzer = \"rust\"\nroots = [\"crates\"]\ntests = []\ntooling = []\nrule_packs = [\"rust\"]\n",
                "select = [\"FPRSR312\"]\n[targets.rust.thresholds]\nmax_helpers_container_buckets = 2\n"
            ),
            files: RUST_WORKSPACE,
            expected_exit_code: 1,
            expected_present: &[
                "--> crates/orders/src/pricing/_helpers",
                "FPRSR312  _helpers/ holds 3 buckets (limit 2); split the owning module by area or move cohesive groups into their own module or crate.",
            ],
            expected_absent: "Threshold override:",
        },
        SizeLimitCheckTestCase {
            description: "path override raises the bucket limit for one crate",
            config: concat!(
                "[targets.rust]\nanalyzer = \"rust\"\nroots = [\"crates\"]\ntests = []\ntooling = []\nrule_packs = [\"rust\"]\n",
                "select = [\"FPRSR312\"]\n[targets.rust.thresholds]\nmax_helpers_container_buckets = 2\n",
                "[[targets.rust.threshold_overrides]]\npaths = [\"crates/orders/**\"]\nreason = \"Order helpers are being split.\"\nthresholds = { max_helpers_container_buckets = 3 }\n"
            ),
            files: RUST_WORKSPACE,
            expected_exit_code: 0,
            expected_present: &[
                "Applied 1 threshold override",
                "Threshold override: max_helpers_container_buckets=3 path=crates/orders/src/pricing/_helpers pattern=crates/orders/** order=0",
                "Found 0 faults",
            ],
            expected_absent: "FPRSR312  ",
        },
        SizeLimitCheckTestCase {
            description: "crate over its code-line limit is reported at its manifest",
            config: concat!(
                "[targets.rust]\nanalyzer = \"rust\"\nroots = [\"crates\"]\ntests = []\ntooling = []\nrule_packs = [\"rust\"]\n",
                "select = [\"FPRSR602\"]\n[targets.rust.thresholds]\nmax_crate_code_lines = 5\n"
            ),
            files: RUST_WORKSPACE,
            expected_exit_code: 1,
            expected_present: &[
                "--> crates/orders/Cargo.toml",
                "FPRSR602  crate holds 6 code lines (limit 5); split it into crates by area.",
            ],
            expected_absent: "Threshold override:",
        },
        SizeLimitCheckTestCase {
            description: "manifest override caps the crate at its current code lines",
            config: concat!(
                "[targets.rust]\nanalyzer = \"rust\"\nroots = [\"crates\"]\ntests = []\ntooling = []\nrule_packs = [\"rust\"]\n",
                "select = [\"FPRSR602\"]\n[targets.rust.thresholds]\nmax_crate_code_lines = 5\n",
                "[[targets.rust.threshold_overrides]]\npaths = [\"crates/orders/Cargo.toml\"]\nreason = \"The orders crate is being split.\"\nthresholds = { max_crate_code_lines = 6 }\n"
            ),
            files: RUST_WORKSPACE,
            expected_exit_code: 0,
            expected_present: &[
                "Threshold override: max_crate_code_lines=6 path=crates/orders/Cargo.toml pattern=crates/orders/Cargo.toml order=0",
                "Found 0 faults",
            ],
            expected_absent: "FPRSR602  ",
        },
        SizeLimitCheckTestCase {
            description: "overrides for unselected rules are not reported as used",
            config: concat!(
                "[targets.rust]\nanalyzer = \"rust\"\nroots = [\"crates\"]\ntests = []\ntooling = []\nrule_packs = [\"rust\"]\n",
                "select = [\"FPRSR312\"]\n",
                "[[targets.rust.threshold_overrides]]\npaths = [\"crates/orders/Cargo.toml\"]\nreason = \"The orders crate is being split.\"\nthresholds = { max_crate_code_lines = 6 }\n"
            ),
            files: RUST_WORKSPACE,
            expected_exit_code: 0,
            expected_present: &["Found 0 faults"],
            expected_absent: "Threshold override:",
        },
        SizeLimitCheckTestCase {
            description: "a manifest rule exception accepts the oversized crate",
            config: concat!(
                "[targets.rust]\nanalyzer = \"rust\"\nroots = [\"crates\"]\ntests = []\ntooling = []\nrule_packs = [\"rust\"]\n",
                "select = [\"FPRSR602\"]\n[targets.rust.thresholds]\nmax_crate_code_lines = 5\n",
                "[[targets.rust.rule_exceptions]]\nrule = \"FPRSR602\"\npath = \"crates/orders/Cargo.toml\"\nreason = \"The orders crate is being split.\"\n"
            ),
            files: RUST_WORKSPACE,
            expected_exit_code: 0,
            expected_present: &["Applied 1 rule exception", "Found 0 faults"],
            expected_absent: "FPRSR602  ",
        },
    ];
    for test_case in &test_cases {
        let repository = tempfile::tempdir().expect("temporary repository");
        write(repository.path().join("fensu.toml"), test_case.config);
        for (path, source) in test_case.files {
            write(repository.path().join(path), source);
        }

        let output = run_check(repository.path());
        let stdout = String::from_utf8_lossy(&output.stdout);
        let cold = run_check_with(repository.path(), &["--cache"]);
        let warm = run_check_with(repository.path(), &["--cache"]);

        assert_eq!(
            output.status.code(),
            Some(test_case.expected_exit_code),
            "{}: {stdout} {}",
            test_case.description,
            String::from_utf8_lossy(&output.stderr)
        );
        for expected in test_case.expected_present {
            assert!(
                stdout.contains(expected),
                "{}: {stdout}",
                test_case.description
            );
        }
        assert!(
            !stdout.contains(test_case.expected_absent),
            "{}: {stdout}",
            test_case.description
        );
        assert_eq!(cold.stdout, warm.stdout, "{}", test_case.description);
        assert_eq!(cold.stdout, output.stdout, "{}", test_case.description);
    }
}
